function slugify(value) {
  return String(value)
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)+/g, "");
}

function makeSeedProducts() {
  return catalog.map((product) => ({
    title: product.title,
    slug: slugify(product.title),
    description: product.description,
    price: product.price,
    category: product.category,
    media: [
      {
        url: product.image,
        publicId: `unsplash/${slugify(product.title)}`,
        type: "image",
        alt: product.title,
      },
    ],
    rating: product.rating,
    stock: product.stock,
    flags: product.flags,
  }));
}

